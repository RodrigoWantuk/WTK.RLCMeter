bool ui_fallback_font_get_glyph(char ch, uint8_t rows[UI_FALLBACK_GLYPH_HEIGHT])
{
    if (rows == NULL)
    {
        return false;
    }

    const fallback_glyph_t *glyph = &g_glyphs[sizeof(g_glyphs) / sizeof(g_glyphs[0]) - 1u];
    for (size_t i = 0u; i < (sizeof(g_glyphs) / sizeof(g_glyphs[0])); i++)
    {
        if (g_glyphs[i].ch == ch)
        {
            glyph = &g_glyphs[i];
            break;
        }
    }

    for (size_t row = 0u; row < UI_FALLBACK_GLYPH_HEIGHT; row++)
    {
        rows[row] = glyph->rows[row];
    }

    return glyph->ch == ch;
}
