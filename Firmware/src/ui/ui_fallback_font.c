bool ui_fallback_font_get_glyph(uint32_t codepoint, uint8_t rows[UI_FALLBACK_GLYPH_HEIGHT])
{
    if (rows == NULL)
    {
        return false;
    }
    if ((codepoint >= (uint32_t)'a') && (codepoint <= (uint32_t)'z'))
    {
        codepoint -= (uint32_t)('a' - 'A');
    }

    const uint8_t ascii = (codepoint <= 0x7Fu) ? (uint8_t)codepoint : (uint8_t)'?';
    const fallback_glyph_t *glyph = &g_glyphs[sizeof(g_glyphs) / sizeof(g_glyphs[0]) - 1u];
    for (size_t i = 0u; i < (sizeof(g_glyphs) / sizeof(g_glyphs[0])); i++)
    {
        if (g_glyphs[i].codepoint == ascii)
        {
            glyph = &g_glyphs[i];
            break;
        }
    }

    for (size_t row = 0u; row < UI_FALLBACK_GLYPH_HEIGHT; row++)
    {
        rows[row] = glyph->rows[row];
    }

    return glyph->codepoint == ascii;
}
